// Packet Siege — build.js
// Joins the parts in packet-siege/src/ (in the order of PARTS) into the one
// script.js the page loads: a header comment, one strict IIFE, every part
// under a `// ── src/<name>.js ──` banner, indented one level, its full-line
// comments stripped (see stripComments).  LF only, with a trailing newline.
//
//   node packet-siege/build.js           writes script.js
//   node packet-siege/build.js --check   writes nothing; exits 1 when
//                                        script.js differs from the build
//
// The art parts (src/sprites-*.js, ASCII maps) are packed on the way in:
// see packArt below and src/unpack-art.js, which restores them at start-up.
//
// Exports build() (returns the text), PARTS, and assemble / stripComments /
// packArt / packPixels / packNumber / PACK_DIGITS for the tests.

'use strict';

const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const PARTS = [
  'core', 'defenders', 'enemies', 'levels', 'levels-late', 'sim', 'enemies-late', 'defenders-late', 'zones', 'bosses',
  'sprites-support', 'sprites-shooters', 'sprites-early', 'sprites-late', 'sprites-floor', 'sprites-fx',
  'sprites-150-def', 'sprites-150-enm-a', 'sprites-150-enm-b', 'sprites-150-boss', 'sprites-150-floor-a',
  'sprites-150-floor-b', 'sprites-150-fx', 'unpack-art', 'sprites',
  'render', 'render-units', 'render-fx', 'render-rules', 'storage', 'ui-text', 'ui-layout', 'ui-page', 'ui-frame',
  'ui-select', 'ui-screens', 'ui-level', 'ui-rules', 'ui-input', 'main'
];

const SRC = path.join(__dirname, 'src');
const OUT = path.join(__dirname, 'script.js');

const HEADER = [
  '// Packet Siege — script.js, GENERATED by packet-siege/build.js: do not edit by hand.',
  '// Edit packet-siege/src/*.js and run `node packet-siege/build.js`.',
  '// Parts, in order: ' + PARTS.map((p) => 'src/' + p + '.js').join(', ') + '.',
  '// Prefix: pks-',
  '// Dependencies: none.',
  '//',
  '// A lane-defense game in a server room: malware walks in from the right along',
  '// five lanes toward the rack; the player spends cycles on defenders that shoot,',
  '// block, trap or make more cycles.  150 levels in fifteen zones, a boss every tenth.',
  '// The simulation (pksNewSim / pksStep) is plain data advanced in fixed steps of',
  '// 1/60 s, deterministic and seeded; rendering only reads it.',
  '//',
  '// Start-up: under Node (module.exports exists) loading only exports the',
  '// functions and tables for the tests; in a browser pksInit runs once the',
  '// document is parsed (on DOMContentLoaded while it is still loading).',
  '//',
  '// The art parts (src/sprites-*.js) are ASCII maps in src/; here they are packed',
  '// by build.js (packArt), and src/unpack-art.js restores them at start-up.',
  '//',
  '// Full-line comments are stripped here (each part keeps its opening line):',
  '// the readable source, every comment included, is packet-siege/src/*.js.'
];

// ── packing the art ─────────────────────────────────────────────────────────
//
// An art part's sprites become one string each, 'name w h pixels', where the
// pixels (row after row, the rows of the ASCII map joined) are a stream of
//   a pixel character ('.' or a palette letter): that pixel;
//   a digit (a character of PACK_DIGITS): a copy, two numbers, the distance
//     back minus 1 and the length minus PACK_MIN, of pixels this part has
//     already produced, earlier sprites included (a copy may overlap itself:
//     distance 1 repeats the last pixel, a run).
// A number is written in PACK_DIGITS: v % 25 as one of the first PACK_ENDS
// (25) digits, which ends it, preceded, when v >= 25, by floor(v / 25) in
// base 10 written with the other ten digits, most significant first.
// The alphabet has no quote, backslash, space, '<' or '>', so the strings need
// no escaping and can never spell the end of a script block or an HTML comment.
//
// packPixels finds the cheapest parse (fewest characters) by dynamic
// programming over the copies a hash chain of 3-pixel keys offers (the
// PACK_CHAIN most recent, at most PACK_MAX long): deterministic, about 0.6 s
// for all the art.

const ART = /^sprites-/;
const PACK_DIGITS = '0123456789!#$%&()*+,-/:;=?@[]^_{|}~';
const PACK_ENDS = 25;
const PACK_MIN = 2;
const PACK_CHAIN = 48;
const PACK_MAX = 384;

function packNumber(v) {
  const base = PACK_DIGITS.length - PACK_ENDS;
  let out = PACK_DIGITS[v % PACK_ENDS];
  for (let carry = Math.floor(v / PACK_ENDS); carry > 0; carry = Math.floor(carry / base)) {
    out = PACK_DIGITS[PACK_ENDS + carry % base] + out;
  }
  return out;
}

// packNumber(v).length, without building the string.
function packSize(v) {
  let size = 1;
  for (let carry = Math.floor(v / PACK_ENDS); carry > 0; carry = Math.floor(carry / (PACK_DIGITS.length - PACK_ENDS))) size++;
  return size;
}

// sprites: the pixel strings of one part, in order; returns their packed
// streams (the same count, each decoding to its own pixels).
function packPixels(sprites) {
  const raw = sprites.join('');
  const n = raw.length;
  const end = new Int32Array(n);      // where the sprite of pixel i ends: no copy crosses it
  let at = 0;
  for (const s of sprites) {
    end.fill(at + s.length, at, at + s.length);
    at += s.length;
  }
  const cost = new Float64Array(n + 1).fill(Infinity);
  const from = new Int32Array(n + 1);
  const dist = new Int32Array(n + 1);  // 0: a pixel; else the copy's distance
  const head = new Map();
  const prev = new Int32Array(n);
  cost[0] = 0;
  for (let i = 0; i < n; i++) {
    if (cost[i] + 1 < cost[i + 1]) {
      cost[i + 1] = cost[i] + 1;
      from[i + 1] = i;
      dist[i + 1] = 0;
    }
    // the longest copy for each length of written distance
    const longest = new Map();
    const limit = Math.min(end[i] - i, PACK_MAX);
    const key = raw.substr(i, 3);
    let p = head.has(key) ? head.get(key) : -1;
    for (let tries = 0; p >= 0 && tries < PACK_CHAIN; tries++, p = prev[p]) {
      let len = 0;
      while (len < limit && raw[p + len] === raw[i + len]) len++;
      const size = packSize(i - p - 1);
      if (len >= PACK_MIN && !(longest.has(size) && longest.get(size).len >= len)) longest.set(size, { d: i - p, len });
    }
    for (const [size, m] of longest) {
      for (let len = PACK_MIN; len <= m.len; len++) {
        const c = cost[i] + size + packSize(len - PACK_MIN);
        if (c < cost[i + len]) {
          cost[i + len] = c;
          from[i + len] = i;
          dist[i + len] = m.d;
        }
      }
    }
    prev[i] = head.has(key) ? head.get(key) : -1;
    head.set(key, i);
  }
  const tokens = [];
  for (let j = n; j > 0; j = from[j]) tokens.push(j);
  const out = sprites.map(() => '');
  let s = 0;
  let stop = sprites.length ? sprites[0].length : 0;
  for (let t = tokens.length - 1; t >= 0; t--) {
    const j = tokens[t];
    const i = from[j];
    while (i >= stop) stop += sprites[++s].length;
    out[s] += dist[j] ? packNumber(dist[j] - 1) + packNumber(j - i - PACK_MIN) : raw[i];
  }
  return out;
}

// The text of an art part, packed: its opening line, then its PKS_ART_*
// variable as an array of 'name w h pixels' strings in the part's order.
// Throws on anything packing could get wrong: a name or pixel outside its
// alphabet, rows that do not match the declared size.
function packArt(text, part) {
  const lines = text.split('\n');
  const decl = /^var (PKS_ART_\w+) = \{$/m.exec(text);
  if (!decl) throw new Error('src/' + part + '.js: no `var PKS_ART_... = {` line');
  const art = vm.runInNewContext(text + '\n;' + decl[1], {});
  const names = Object.keys(art);
  for (const name of names) {
    const s = art[name];
    if (!/^[a-z0-9-]+$/.test(name)) throw new Error('src/' + part + '.js: sprite name ' + JSON.stringify(name));
    if (!Array.isArray(s.rows) || s.rows.length !== s.h || s.rows.some((r) => typeof r !== 'string' || r.length !== s.w)) {
      throw new Error('src/' + part + '.js: ' + name + ' is not ' + s.w + 'x' + s.h);
    }
    const bad = /[^A-Za-z.]/.exec(s.rows.join(''));
    if (bad) throw new Error('src/' + part + '.js: ' + name + ' has the pixel ' + JSON.stringify(bad[0]));
  }
  const packed = packPixels(names.map((name) => art[name].rows.join('')));
  return [lines[0], 'var ' + decl[1] + ' = ['].concat(names.map((name, i) =>
    '  \'' + name + ' ' + art[name].w + ' ' + art[name].h + ' ' + packed[i] + '\'' + (i < names.length - 1 ? ',' : ''))).concat(['];']).join('\n');
}

// ── stripping comments ──────────────────────────────────────────────────────
//
// script.js keeps the code of every part as it is (indented, not minified)
// but drops its full-line `//` comments: a line whose first non-blank
// characters are `//`.  Kept: each part's opening line (`// ── name: …`, the
// first line of the part) and everything build() adds (the header, the
// `// ── src/<name>.js ──` banners).  A comment after code on the same line
// stays, and so does any line that is not a comment: a `//` inside a string
// or a regular expression is on a code line, and a line that continues a
// string (the line before ends in a backslash) is never taken for a comment.
// The readable source with every comment is src/.

// The lines of a part's text without its full-line comments (the first line
// kept).
function stripComments(text) {
  const lines = text.split('\n');
  const out = [lines[0]];
  for (let i = 1; i < lines.length; i++) {
    if (/^\s*\/\//.test(lines[i]) && !/\\$/.test(lines[i - 1])) continue;
    out.push(lines[i]);
  }
  return out.join('\n');
}

// The unsafe check: the page embeds script.js in a script block, so none of
// these may appear in it.  It runs on the parts as written too, comments
// included, so stripping can never hide one that src/ has.
function checkSafe(text) {
  const unsafe = /<!--|-->|<\/script/i.exec(text);
  if (unsafe) throw new Error('script.js would contain ' + JSON.stringify(unsafe[0]) + ' at offset ' + unsafe.index);
}

// The generated file from the parts' texts (a map part -> source text, LF);
// build() reads them from src/.
function assemble(sources) {
  const out = HEADER.slice();
  const full = [];
  out.push('', '(function () {', '  \'use strict\';');
  for (const part of PARTS) {
    const source = sources[part].replace(/\s+$/, '');
    full.push(source);
    const text = stripComments(ART.test(part) ? packArt(source, part) : source);
    out.push('', '  // ── src/' + part + '.js ──', '');
    for (const line of text.split('\n')) out.push(line ? '  ' + line : '');
  }
  out.push('})();', '');
  checkSafe(full.join('\n'));
  const script = out.join('\n');
  checkSafe(script);
  return script;
}

function build() {
  const sources = {};
  for (const part of PARTS) sources[part] = fs.readFileSync(path.join(SRC, part + '.js'), 'utf8').replace(/\r\n/g, '\n');
  return assemble(sources);
}

if (require.main === module) {
  const text = build();
  if (process.argv.includes('--check')) {
    // a checkout with core.autocrlf=true has CRLF on disk: compare as LF
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
    if (current !== text) {
      console.error('packet-siege/script.js is stale: run `node packet-siege/build.js`.');
      process.exit(1);
    }
  } else {
    fs.writeFileSync(OUT, text);
  }
}

module.exports = { build, assemble, stripComments, PARTS, packArt, packPixels, packNumber, PACK_DIGITS };
